import assert from 'node:assert/strict';
import {newWorkerRequests} from '../app/request-notifications.ts';
import type {WorkerRequest} from '../app/model.ts';
import {notificationSnapshot,receiveNotifications,dismissNotification,subscribeNotifications} from '../app/request-notification-store';
const request=(id:string,created:string,status:WorkerRequest['status']='pending'):WorkerRequest=>({id,created,status,name:'Worker '+id,trade:'Mason',siteId:'s',createdBy:'auditor1'});
const seen=new Set(['old']);
const rows=[request('old','2026-11-01'),request('new','2026-11-02'),request('latest','2026-11-03'),request('accepted','2026-11-04','accepted'),request('declined','2026-11-05','declined')];
assert.deepEqual(newWorkerRequests(rows,seen).map(r=>r.id),['latest','new']);
for(const r of newWorkerRequests(rows,seen))seen.add(r.id);
assert.equal(newWorkerRequests(rows,seen).length,0,'Polling must not repeat already displayed notifications');
assert.equal(newWorkerRequests(rows,new Set()).length,3,'Another admin/browser can see its own unread pending requests');
let updates=0;const unsubscribe=subscribeNotifications('workspace:admin1',()=>updates++);
receiveNotifications('workspace:admin1',rows);
assert.deepEqual(notificationSnapshot('workspace:admin1'),['latest','new','old']);
const snapshot=notificationSnapshot('workspace:admin1');receiveNotifications('workspace:admin1',rows);
assert.equal(notificationSnapshot('workspace:admin1'),snapshot,'Unchanged polls must keep a stable snapshot');
dismissNotification('workspace:admin1','new');receiveNotifications('workspace:admin1',rows);
assert.deepEqual(notificationSnapshot('workspace:admin1'),['latest','old'],'Dismissed request must not return on next poll');
receiveNotifications('workspace:admin1',rows.map(r=>({...r,status:'accepted'})));
assert.equal(notificationSnapshot('workspace:admin1').length,0,'Another admin decision must remove visible popups');
receiveNotifications('workspace:admin2',rows);
assert.equal(notificationSnapshot('workspace:admin2').length,3,'Admins must have separate notification histories');
assert.equal(updates,3);unsubscribe();
console.log('PASS: new pending requests only, latest-first display, repeated-poll deduplication, and independent read history');
