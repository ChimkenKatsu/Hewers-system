import assert from 'node:assert/strict';
import {googleRows} from '../app/google-export.ts';
import {emptyState} from '../app/model.ts';
const state=emptyState();state.workers=[{id:'w',name:'=IMPORTXML("bad")',trade:'Mason',siteId:'s'}];state.sites=[{id:'s',name:'Site A',location:'Test'}];state.attendance=[{id:'a',workerId:'w',siteId:'s',timeIn:'2026-11-02T00:00:00Z',timeOut:null,method:'Face-assisted pilot',note:'Private note'}];
state.materials=[{id:'m',name:'Cement',siteId:'s',unit:'bags',balance:3,minimum:5}];
const rows=googleRows(state);assert.equal(rows.Attendance[1][1],state.workers[0].name);assert.equal(rows.Attendance[1][2],'Site A');assert.equal(rows.Attendance[1][4],'');assert.equal(rows.Inventory[1][3],3);assert.equal(rows.Movements.length,1);assert.ok(!JSON.stringify(rows).includes('Private note'));assert.deepEqual(Object.keys(rows),['Attendance','Inventory','Movements']);
const cell=(rows:(string|number)[][],name:string)=>rows[1][rows[0].indexOf(name)];
assert.equal(cell(rows.Attendance,'Trade / role'),'Mason');
assert.equal(cell(rows.Attendance,'Time in (PHT)'),'2026-11-02 08:00:00');
assert.equal(cell(rows.Attendance,'Elapsed hours (no break deduction)'),'');
assert.equal(cell(rows.Attendance,'Status'),'Checked in');
assert.equal(cell(rows.Inventory,'Quantity below minimum'),2);
state.attendance[0].timeOut='2026-11-02T09:30:00Z';
state.attendance[0].timeOutMethod='Manual';
state.movements=[{id:'v',materialId:'m',siteId:'s',type:'Issue',quantity:2,note:'Private movement note',created:'2026-11-02T17:00:00Z',actor:'operator'}];
const complete=googleRows(state);
assert.equal(cell(complete.Attendance,'Elapsed hours (no break deduction)'),9.5);
assert.equal(cell(complete.Attendance,'Status'),'Completed');
assert.equal(cell(complete.Movements,'Stock change (+/-)'),-2);
assert.equal(cell(complete.Movements,'Recorded date (PHT)'),'2026-11-03');
assert.equal(cell(complete.Movements,'Unit'),'bags');
assert.ok(!JSON.stringify(complete).includes('Private movement note'));
const csv=googleRows(state,{includeNotes:true});
assert.equal(cell(csv.Attendance,'Note'),'Private note');
assert.equal(cell(csv.Movements,'Reference / reason'),'Private movement note');
for(const report of Object.values(csv))for(const row of report)assert.equal(row.length,report[0].length,'Each row matches the expanded column schema');
state.materials[0].balance=5;
assert.equal(cell(googleRows(state).Inventory,'Stock status'),'Low stock');
assert.equal(cell(googleRows(state).Inventory,'Quantity below minimum'),0);
console.log('PASS: explicit Google export columns, names/sites, quantities, empty histories, private-note exclusion. Values must be sent with RAW input.');
