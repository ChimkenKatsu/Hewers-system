import assert from 'node:assert/strict';
import {emptyState} from '../app/model';
import {applyOperation} from '../app/operations';
import {attendanceShift,checkShiftEntry} from '../app/shift-policy';
import {authorize,visibleState,type Access} from '../app/permissions';
import {missingTimeouts} from '../app/attendance-reminders';
import {googleRows} from '../app/google-export';
const time=(clock:string,date='2026-11-10')=>date+'T'+clock+':00+08:00';
let state=emptyState();state.sites=[{id:'s',name:'Site',location:'Test'}];state.workers=[{id:'w',name:'Worker',trade:'Mason',siteId:'s'}];
const admin:Access={owner:'o',userId:'a',email:'admin',role:'administrator',siteIds:[]};const auditor:Access={...admin,role:'auditor',siteIds:['s']};
const enter=(at:string)=>applyOperation(state,'attendance',{workerId:'w',type:'in',note:'Test entry'},'auditor',time(at));
assert.equal(attendanceShift(enter('07:50').attendance[0]).lateMinutes,0);
assert.equal(attendanceShift(enter('08:00').attendance[0]).lateMinutes,0);
assert.equal(attendanceShift(enter('08:05').attendance[0]).lateMinutes,5);
assert.throws(()=>enter('17:00'),/closes/);
state=enter('08:00');assert.equal(state.attendance[0].shiftKind,'regular');
assert.throws(()=>checkShiftEntry(state,'w',time('09:00')),/open/);
state=applyOperation(state,'attendance',{workerId:'w',type:'out'},'auditor',time('17:00'));
assert.throws(()=>checkShiftEntry(state,'w',time('17:01')),/already recorded/);
assert.throws(()=>checkShiftEntry(state,'w',time('16:00')),/already recorded/);
const payload={workerId:'w',date:'2026-11-10',endTime:'20:00',reason:'Approved concrete finishing work'};
assert.throws(()=>authorize(auditor,state,'overtime-approve',payload),/FORBIDDEN/);authorize(admin,state,'overtime-approve',payload);
assert.throws(()=>applyOperation(state,'overtime-approve',{...payload,endTime:'16:30'},'admin',time('17:01')),/after/);
assert.throws(()=>applyOperation(state,'overtime-approve',{...payload,date:'2026-11-11'},'admin',time('17:01')),/today/);
state=applyOperation(state,'overtime-approve',payload,'admin',time('17:01'));
assert.throws(()=>applyOperation(state,'overtime-approve',payload,'admin',time('17:02')),/unused/);
assert.equal(visibleState(state,auditor).overtimeApprovals?.length,1);
assert.equal(visibleState(state,{...auditor,siteIds:[]}).overtimeApprovals?.length,0);
const revoked=applyOperation(state,'overtime-revoke',{approvalId:state.overtimeApprovals![0].id},'admin',time('17:02'));
assert.throws(()=>checkShiftEntry(revoked,'w',time('17:03')),/already recorded/);
assert.throws(()=>checkShiftEntry(state,'w',time('20:00')),/already recorded/);
state=applyOperation(state,'attendance',{workerId:'w',type:'in',note:'Overtime scan'},'auditor',time('17:05'));
const overtime=state.attendance[1];assert.equal(overtime.shiftKind,'overtime');assert.equal(state.overtimeApprovals![0].usedAttendanceId,overtime.id);assert.equal(attendanceShift(overtime).lateMinutes,0);
assert.throws(()=>applyOperation(state,'overtime-revoke',{approvalId:state.overtimeApprovals![0].id},'admin',time('17:06')),/unused/);
assert.equal(missingTimeouts(state,auditor,Date.parse(time('19:59'))).length,0);
assert.equal(missingTimeouts(state,auditor,Date.parse(time('20:00'))).length,1);
state=applyOperation(state,'attendance',{workerId:'w',type:'out'},'auditor',time('20:10'));
assert.equal(state.attendance[1].timeOut,time('20:10'),'Keep actual departure even after approved end');
assert.throws(()=>checkShiftEntry(state,'w',time('20:11')),/already recorded/);
assert.equal(checkShiftEntry(state,'w',time('08:00','2026-11-11')).kind,'regular');
const rows=googleRows(state).Attendance;assert.equal(rows[2][rows[0].indexOf('Shift')],'Overtime');assert.equal(rows[2][rows[0].indexOf('Overtime approval ID')],overtime.overtimeApprovalId);
console.log('PASS: PHT regular hours, late arrival, repeat denial, admin/site scope, one-use overtime, expiry/revocation, actual checkout, reminders and exports');
